CREATE TABLE users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(120) UNIQUE NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  role ENUM('user','admin') DEFAULT 'user'
);
CREATE TABLE readings (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  device_id VARCHAR(40), user_id INT NULL,
  value_enc VARBINARY(255) NOT NULL,   -- temperatura criptografada
  ts TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE commands (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(30), value_enc VARBINARY(255),
  user_id INT, acked BOOL DEFAULT 0,
  ts TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE logs (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NULL, ip VARCHAR(45),
  action_enc VARBINARY(500), ts TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);